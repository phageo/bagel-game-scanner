# the dictionaries below are kept in engine_hashes.bin beside this module, every SHA-256 as its 32
# bytes (gamescan.bintable)
from . import bintable as _bintable  # noqa: E402

_TABLES = _bintable.beside(__file__, 'engine_hashes.bin')

# SHA-256 of the file -> (its name in the archive, index into ARCHIVES of the first
# archive that contains it). Programs and libraries; of the NW.js archives every
# file (the table is the official distribution - a program by its file name, any
# other file by its path in the archive); of the Ren'Py SDKs also the shell launcher
# (renpy.sh). The scanner asks the table for programs and for that launcher, and
# for the note SCRIPT-LIMIT-001.
KNOWN = _TABLES['KNOWN']

# Ren'Py engine scripts (renpy/ and lib/ of an SDK): SHA-256 of the file ->
# (its path in the SDK, index into ARCHIVES of the first archive that contains it)
SCRIPTS = _TABLES['SCRIPTS']

# compiled Ren'Py engine scripts by what they contain: a compiled script carries the
# folder of whoever compiled it, so the file itself is never the same twice.
# gamescan.unpack.rpyc.content_key -> (path in the SDK, index into ARCHIVES)
SCRIPT_CONTENT = _TABLES['SCRIPT_CONTENT']

# the NW.js launcher without its resource section (RPG Maker MV / MZ put the game's icon
# into nw.exe): gamescan.pe.resource_frame_key -> (name, index into ARCHIVES, entry point)
LAUNCHERS = _TABLES['LAUNCHERS']

# the programs (.exe) of the Ren'Py SDKs without their resource section (a game ships the
# start program renamed, with its own icon): gamescan.pe.resource_frame_key -> (name, index
# into ARCHIVES of the first archive that holds it, entry point)
RENPY_PROGRAMS = _TABLES['RENPY_PROGRAMS']


def verified(sha256: str) -> Optional[str]:
    """What official file has this SHA-256 (None: not in the table)."""
    entry = KNOWN.get((sha256 or "").lower())
    if entry is None:
        return None
    engine, version, build = ARCHIVES[entry[1]][:3]
    return "%s - %s %s (%s)" % (entry[0], engine, version, build)


def source(sha256: str) -> Optional[str]:
    """URL of the official archive the file with this SHA-256 comes from."""
    entry = KNOWN.get((sha256 or "").lower())
    return None if entry is None else ARCHIVES[entry[1]][3]


def verified_shell_launcher(sha256: str) -> Optional[str]:
    """Which official Ren'Py shell launcher (``renpy.sh`` of an SDK) has this
    SHA-256 (None: none) - a game ships a copy of it under the game's name."""
    entry = KNOWN.get((sha256 or "").lower())
    if entry is None or entry[0] != "renpy.sh" or ARCHIVES[entry[1]][0] != "Ren'Py":
        return None
    return verified(sha256)


def verified_script(sha256: str, content_key: Optional[str] = None) -> Optional[str]:
    """Which official Ren'Py engine script this is (None: not in the tables):
    by the SHA-256 of the file, or - a compiled script - by what it contains
    (``gamescan.unpack.rpyc.content_key``)."""
    entry = SCRIPTS.get((sha256 or "").lower())
    if entry is None and content_key:
        entry = SCRIPT_CONTENT.get(content_key)
    if entry is None:
        return None
    engine, version, build = ARCHIVES[entry[1]][:3]
    return "%s - %s %s (%s)" % (entry[0], engine, version, build)


def renpy_versions() -> tuple:
    """The Ren'Py versions whose engine scripts are in the tables."""
    return tuple(row[1] for row in ARCHIVES if row[0] == "Ren'Py")


